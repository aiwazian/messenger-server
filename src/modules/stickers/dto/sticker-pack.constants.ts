/*
 * Ограничения набора стикеров.
 *
 * Лежат отдельно, потому что нужны и DTO (отказать до базы), и сервису
 * (проверить уже собранный состав). Два разных числа в двух местах дали бы
 * валидацию, которая пропускает запрос и падает глубже.
 */

/** Название набора: столько влезает в карточку набора без обрезки. */
export const MAX_STICKER_PACK_NAME_LENGTH = 15

/*
 * Имя набора в ссылке-приглашении.
 *
 * Оно попадаёт в адрес, поэтому разрешены только символы, которые не надо
 * кодировать и которые нельзя спутать при наборе вручную.
 */
export const MIN_STICKER_PACK_USERNAME_LENGTH = 3
export const MAX_STICKER_PACK_USERNAME_LENGTH = 32
export const STICKER_PACK_USERNAME_PATTERN = /^[a-zA-Z0-9_]+$/

/**
 * Предел стикеров в одном наборе.
 *
 * Набор отдаётся целиком и одним ответом, а клиент рисует его сеткой без
 * подгрузки страницами, так что размер ответа должен оставаться конечным.
 */
export const MAX_STICKERS_PER_PACK = 120
