/**
 * Политика анонимного чтения бакета.
 *
 * Лежит рядом с адаптером, а не в constants: формат правил — часть S3, а не
 * доменной модели приложения. Сервисы говорят только «эти каталоги публичные».
 */

/**
 * Идентификатор правила.
 *
 * Фиксированный: по нему в панели провайдера видно, что правило поставлено
 * приложением, а не руками.
 */
export const PUBLIC_READ_SID = 'PublicRead'

/**
 * Политика, открывающая чтение перечисленных каталогов всем.
 *
 * Разрешается только s3:GetObject: без s3:ListBucket содержимое каталога
 * нельзя перебрать, без s3:PutObject — нельзя записать. Скачать можно
 * только то, чей ключ уже известен, а ключи — случайные UUID.
 *
 * Principal записан полной формой { AWS: ['*'] }: короткую "*" принимают не все
 * S3-совместимые реализации, а полная работает везде.
 *
 * Важно: у S3 нет операции «добавить правило» — политика всегда заменяется
 * целиком. Всё, что нужно бакету, описывается здесь, иначе при следующем
 * старте сервера правило из панели будет потеряно.
 */
export function buildPublicReadPolicy(bucket: string, directories: string[]): string {
	return JSON.stringify({
		Version: '2012-10-17',
		Statement: [
			{
				Sid: PUBLIC_READ_SID,
				Effect: 'Allow',
				Principal: { AWS: ['*'] },
				Action: ['s3:GetObject'],
				Resource: directories.map((directory) => `arn:aws:s3:::${bucket}/${directory}/*`)
			}
		]
	})
}
