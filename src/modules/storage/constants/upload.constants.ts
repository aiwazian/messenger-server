/** Предельный размер загружаемого файла: 1 ГБ. */
export const MAX_UPLOAD_SIZE_BYTES = 1024 * 1024 * 1024

/**
 * Пустой файл не имеет смысла и ломает определение типа по сигнатуре:
 * нижняя граница нужна и в политике S3, чтобы нельзя было залить 0 байт.
 */
export const MIN_UPLOAD_SIZE_BYTES = 1

/**
 * Предельный размер одного стикера: 512 КБ.
 *
 * Общий потолок в гигабайт здесь бессмыслен: клиент присылает уже сжатый
 * webp 512x512, который весит десятки килобайт. Потолок зашивается в
 * политику загрузки, поэтому в публичный бакет нельзя залить тяжёлый файл
 * даже с полученной формой.
 */
export const MAX_STICKER_SIZE_BYTES = 512 * 1024

/**
 * Единственный допустимый формат стикера.
 *
 * webp держит прозрачность и весит заметно меньше png, а один формат
 * вместо нескольких избавляет от разбора вариантов и на сервере, и на
 * клиенте. Анимированные стикеры появятся отдельным форматом (webm),
 * когда до них дойдёт дело.
 */
export const STICKER_MIME_TYPE = 'image/webp'

/** Время жизни формы загрузки. */
export const UPLOAD_URL_TTL_SECONDS = 3600

/** Время жизни ссылки на скачивание. */
export const DOWNLOAD_URL_TTL_SECONDS = 3600

/**
 * Сколько байт читаем с начала объекта, чтобы определить реальный тип.
 * Сигнатуры всех поддерживаемых форматов укладываются в первые килобайты.
 */
export const MIME_SNIFF_BYTES = 4096
