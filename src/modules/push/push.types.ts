import { ChatType } from '../../common/enums/chat-type.enum'

export class PushNotificationPayload {
	title: string
	body: string
	chatId: string

	/**
	 * Категория чата для настроек уведомлений.
	 *
	 * Передаётся явно, потому что по chatId её не восстановить: в групповом
	 * уведомлении там лежит id отправителя, а не id группы, и такое сообщение
	 * сошло бы за личное.
	 */
	chatType?: ChatType

	/**
	 * Когда сообщение было отправлено, в миллисекундах.
	 *
	 * Клиент ставит это время в setWhen() уведомления. Без него в шторке стоял бы
	 * момент доставки: сообщение, пролежавшее час в очереди FCM или дождавшееся
	 * выхода устройства из спящего режима, выглядело бы только что написанным.
	 */
	sendTime?: string
}
