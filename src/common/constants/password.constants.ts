/*
 * Единая парольная политика проекта.
 *
 * Раньше правила задавались в каждом DTO отдельно и расходились между собой:
 * регистрация принимала 5–64 символа без пробелов, смена пароля — 5–32 по
 * белому списку символов без кириллицы, сброс — от 5 без верхней границы.
 * Из-за этого пароль длиной 40 символов проходил регистрацию, но его нельзя
 * было сменить, а кириллический пароль ломался только на смене.
 *
 * Теперь значения живут здесь: правки в этом файле применяются сразу ко всем
 * сценариям — регистрации, входу, смене и сбросу пароля.
 */

/** Минимальная длина пароля. */
export const PASSWORD_MIN_LENGTH = 5

/** Максимальная длина пароля. */
export const PASSWORD_MAX_LENGTH = 64

/**
 * Разрешены любые непробельные символы, включая кириллицу и юникод.
 *
 * Белый список символов здесь намеренно не используется: он отсекал бы
 * пароли уже зарегистрированных пользователей и снижал бы энтропию, ничего
 * не давая взамен — пароль всё равно хранится только в виде bcrypt-хэша.
 */
export const PASSWORD_REGEX = /^\S+$/

/** Сообщение об ошибке для PASSWORD_REGEX. */
export const PASSWORD_REGEX_MESSAGE = 'password must not contain spaces'
