/**
 * Что клиент может сделать с заголовком «Forwarded from» / превью ответа.
 *
 * Считается на сервере при каждом чтении сообщения, а не при отправке:
 * если пользователь позже подпишется на приватный канал, заголовок станет
 * кликабельным сам, без перезаписи истории.
 */
export enum ForwardSourceAccess {
	/** Источник можно открыть: публичный канал/группа, подписка, разрешённый профиль. */
	OPEN = 'OPEN',
	/** Источник существует, но открывать нельзя — клиент показывает тултип. */
	RESTRICTED = 'RESTRICTED',
	/** Источник удалён: заголовок не кликабельный и без тултипа. */
	UNAVAILABLE = 'UNAVAILABLE'
}
