/**
 * Категория файла, которую клиент объявляет до начала загрузки.
 *
 * По ней строится политика presigned POST: S3 сам отклонит загрузку, если
 * Content-Type не совпадёт с объявленным. Первые четыре значения намеренно
 * совпадают с AttachmentType из схемы Prisma, но enum отдельный: категория
 * описывает загрузку, а не вложение сообщения — ни аватары, ни стикеры
 * вложениями не являются.
 */
export enum UploadCategory {
	IMAGE = 'IMAGE',
	VIDEO = 'VIDEO',
	VOICE = 'VOICE',
	FILE = 'FILE',

	/**
	 * Стикер: картинка с более строгими правилами, чем у обычного фото.
	 *
	 * Отдельная категория, а не IMAGE: у стикера единственный допустимый
	 * формат и свой потолок размера, а файл попадает в публичный бакет —
	 * протащить туда произвольную картинку под видом стикера нельзя.
	 */
	STICKER = 'STICKER'
}
