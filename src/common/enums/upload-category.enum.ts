/**
 * Категория файла, которую клиент объявляет до начала загрузки.
 *
 * По ней строится политика presigned POST: S3 сам отклонит загрузку, если
 * Content-Type не совпадёт с объявленным. Значения намеренно совпадают с
 * AttachmentType из схемы Prisma, но enum отдельный: категория описывает
 * загрузку, а не вложение сообщения — аватары вложениями не являются.
 */
export enum UploadCategory {
	IMAGE = 'IMAGE',
	VIDEO = 'VIDEO',
	VOICE = 'VOICE',
	FILE = 'FILE'
}
